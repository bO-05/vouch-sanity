import {defineArrayMember, defineField, defineType} from 'sanity'
import {FLAG_ROUTES, TRIAGE_OUTCOMES} from './constants'

/** One line of a request's checklist: a catalog item and how many units are needed. */
export const needItem = defineType({
  name: 'needItem',
  title: 'Checklist line',
  type: 'object',
  fields: [
    defineField({
      name: 'supplyItem',
      title: 'Supply item',
      type: 'reference',
      to: [{type: 'supplyItem'}],
      options: {filter: 'active != false'},
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'quantity',
      type: 'number',
      description: "Units requested. The server caps this at the item's max per household.",
      validation: (rule) => rule.required().integer().min(1).max(50),
    }),
    defineField({
      name: 'pledgedQty',
      title: 'Pledged quantity',
      type: 'number',
      readOnly: true,
      initialValue: 0,
      description:
        'Maintained by the server in the same transaction as each pledge document. Not edited by hand.',
      validation: (rule) => rule.integer().min(0),
    }),
  ],
  validation: (rule) =>
    rule.custom((line: {quantity?: number; pledgedQty?: number} | undefined) =>
      line && typeof line.quantity === 'number' && (line.pledgedQty ?? 0) > line.quantity
        ? 'More units are pledged than requested.'
        : true,
    ),
  preview: {
    select: {
      name: 'supplyItem.name',
      unit: 'supplyItem.unit',
      quantity: 'quantity',
      pledged: 'pledgedQty',
    },
    prepare: ({name, unit, quantity, pledged}) => ({
      title: `${quantity ?? '?'} × ${name ?? 'Unknown item'}`,
      subtitle: [unit, `${pledged ?? 0} pledged`].filter(Boolean).join(' · '),
    }),
  },
})

/** A yes/no concern Jev raised about a request, with its probability. */
export const triageFlag = defineType({
  name: 'triageFlag',
  title: 'Flag',
  type: 'object',
  fields: [
    defineField({name: 'code', type: 'string', validation: (rule) => rule.required()}),
    defineField({name: 'label', type: 'string'}),
    defineField({
      name: 'probability',
      type: 'number',
      description: "Jev's probability (0 to 1) that the flag applies.",
      validation: (rule) => rule.min(0).max(1),
    }),
  ],
  preview: {
    select: {label: 'label', code: 'code', probability: 'probability'},
    prepare: ({label, code, probability}) => ({
      title: label ?? code,
      subtitle: typeof probability === 'number' ? `p = ${probability.toFixed(2)}` : undefined,
    }),
  },
})

/** What triage concluded and why. Written by the server; never typed by hand. */
export const triageSummary = defineType({
  name: 'triageSummary',
  title: 'Triage summary',
  type: 'object',
  readOnly: true,
  fields: [
    defineField({name: 'outcome', type: 'string', options: {list: TRIAGE_OUTCOMES}}),
    defineField({
      name: 'reasons',
      type: 'array',
      of: [defineArrayMember({type: 'string'})],
      description:
        'Why it went to a human. Composed by code from flags and policy thresholds, never generated by a model.',
    }),
    defineField({name: 'flags', type: 'array', of: [defineArrayMember({type: 'triageFlag'})]}),
    defineField({
      name: 'minConfidence',
      title: 'Lowest answer confidence',
      type: 'number',
      validation: (rule) => rule.min(0).max(1),
    }),
    defineField({
      name: 'decision',
      title: 'Jev decision',
      type: 'reference',
      to: [{type: 'decision'}],
      weak: true,
    }),
    defineField({name: 'decidedAt', type: 'datetime'}),
  ],
})

/** One line of a receipt, after the uploader corrected the OCR output. */
export const receiptLine = defineType({
  name: 'receiptLine',
  title: 'Receipt line',
  type: 'object',
  fields: [
    defineField({name: 'text', type: 'string', validation: (rule) => rule.required()}),
    defineField({
      name: 'amount',
      type: 'number',
      description: 'Price printed on the line, if one was read.',
    }),
    defineField({
      name: 'ocrSimilarity',
      title: 'Similarity to what OCR read',
      type: 'number',
      description:
        'Computed by the server: 1 means the uploader left the line as OCR read it from the photo. Matched lines below the policy threshold go to a verifier.',
      validation: (rule) => rule.min(0).max(1),
    }),
  ],
  preview: {
    select: {text: 'text', amount: 'amount'},
    prepare: ({text, amount}) => ({
      title: text,
      subtitle: typeof amount === 'number' ? `$${amount.toFixed(2)}` : undefined,
    }),
  },
})

