/** A yes/no question Jev answers about every request (policy-as-content). */
export const flagQuestion = defineType({
  name: 'flagQuestion',
  title: 'Flag question',
  type: 'object',
  fields: [
    defineField({
      name: 'code',
      type: 'string',
      description: 'Stable id used by code and stored on requests (snake_case).',
      validation: (rule) =>
        rule
          .required()
          .regex(/^[a-z][a-z0-9_]*$/, {name: 'snake_case'})
          .max(40),
    }),
    defineField({
      name: 'label',
      type: 'string',
      description: 'Short reason shown to verifiers and requesters.',
      validation: (rule) => rule.required().max(60),
    }),
    defineField({
      name: 'question',
      type: 'text',
      rows: 3,
      description:
        'Sent verbatim to Jev as a yes/no (Noul) question. Refer to the request as `request` (with backticks): that is the name of the field Jev reads.',
      validation: (rule) => rule.required().min(20).max(500),
    }),
    defineField({
      name: 'routesTo',
      title: 'When it fires',
      type: 'string',
      options: {list: FLAG_ROUTES, layout: 'radio'},
      initialValue: 'review',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'threshold',
      title: 'Own threshold (optional)',
      type: 'number',
      description:
        'Fires at or above this probability instead of the global maximum flag probability. Use a lower number where a miss costs more than a false alarm (emergencies).',
      validation: (rule) => rule.min(0).max(1),
    }),
    defineField({name: 'enabled', type: 'boolean', initialValue: true}),
  ],
  preview: {
    select: {label: 'label', code: 'code', enabled: 'enabled', routesTo: 'routesTo'},
    prepare: ({label, code, enabled, routesTo}) => ({
      title: enabled === false ? `${label} (disabled)` : label,
      subtitle: [code, routesTo].filter(Boolean).join(' · '),
    }),
  },
})

function probability(name: string, title: string, description: string) {
  return defineField({
    name,
    title,
    type: 'number',
    description,
    validation: (rule) => rule.required().min(0).max(1),
  })
}

